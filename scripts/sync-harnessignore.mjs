function buildBlock(plan, version) {
  return [
    BEGIN,
    `# baseline: upstream harness-setting v${version ?? '(local-dir)'}`,
    `# 패턴 ${plan.patterns.length}개 (디렉토리 ${plan.dirPatterns.length} / 개별 ${plan.filePatterns.length})` +
      ` — upstream 부재 경로 ${plan.targets.length}건 커버`,
    ...plan.patterns,
    END,
  ].join('\n');
}

function replaceBlock(existing, block) {
  const beginIdx = existing.indexOf(BEGIN);
  const endIdx = existing.indexOf(END);

  if (beginIdx === -1 && endIdx === -1) {
    const trimmed = existing.replace(/\n+$/, '');
    return trimmed ? `${trimmed}\n\n${block}\n` : `${block}\n`;
  }
  if (beginIdx === -1 || endIdx === -1 || endIdx < beginIdx) {
    // 손상된 블록을 추측 복구하면 조용한 오염이 된다 — fail-fast
    throw new Error(`${IGNORE_PATH} 의 자동 생성 블록이 손상됨 — 수동 복구 필요`);
  }
  const before = existing.slice(0, beginIdx).replace(/\n+$/, '');
  const after = existing.slice(endIdx + END.length).replace(/^\n+/, '');
  // before 가 비면 선두 개행을 넣지 않는다 — 넣으면 재생성이 비멱등이 되어
  // `--check` 가 영구 drift 로 오탐한다 (self-test roundtrip 케이스에서 실측).
  return `${before ? `${before}\n\n` : ''}${block}\n${after ? `\n${after}` : ''}`;
}

