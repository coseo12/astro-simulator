/**
 * upstream 부재 경로를 최소 패턴 집합으로 압축.
 *
 * 압축 규칙: 어떤 upstream 파일도 갖지 않는 **가장 얕은** 조상 디렉토리를 `dir/` 로 낸다.
 * 안전 근거 — 그 디렉토리 아래에 upstream 파일이 0 개이므로 프루닝해도 upstream 파일이
 * `walkTracked` 에서 사라지지 않는다 (불변식 S 자동 충족).
 *
 * @param {string[]} upstreamPaths
 * @param {string[]} localPaths
 * @returns {{patterns: string[], targets: string[], dirPatterns: string[], filePatterns: string[]}}
 */
export function computeIgnorePlan(upstreamPaths, localPaths) {
  const upstream = new Set(upstreamPaths);
  const targets = localPaths.filter((p) => !upstream.has(p)).sort();

  // upstream 파일을 가진 모든 조상 디렉토리 — 이 집합에 속하면 압축 불가
  const upstreamDirs = new Set();
  for (const p of upstream) {
    const seg = p.split('/');
    for (let i = 1; i < seg.length; i++) upstreamDirs.add(seg.slice(0, i).join('/'));
  }

  const dirPatterns = new Set();
  for (const p of targets) {
    const seg = p.split('/');
    for (let i = 1; i < seg.length; i++) {
      const d = seg.slice(0, i).join('/');
      if (!upstreamDirs.has(d)) {
        dirPatterns.add(`${d}/`);
        break; // 가장 얕은 안전 디렉토리에서 멈춘다
      }
    }
  }

  const dirList = [...dirPatterns].sort();
  const covered = (p) => dirList.some((d) => p.startsWith(d));
  const filePatterns = targets.filter((p) => !covered(p));

  return {
    patterns: [...dirList, ...filePatterns].sort(),
    targets,
    dirPatterns: dirList,
    filePatterns,
  };
}

/**
 * 불변식 (S) — upstream 존재 경로가 하나라도 무시되면 안 된다.
 * @param {string} ignoreText — `.harnessignore` 전문 (수동 섹션 포함)
 * @param {string[]} upstreamPaths
 * @returns {string[]} 위반 경로 목록
 */
export function findUpstreamPathsIgnored(ignoreText, upstreamPaths) {
  const patterns = loadPatternsFromText(ignoreText);
  return upstreamPaths.filter((p) => isIgnored(p, patterns));
}

/**
 * 불변식 (K) — 대상 경로가 전부 매칭되는지.
 * @param {string} ignoreText
 * @param {string[]} targets
 * @returns {string[]} 미커버 경로 목록
 */
export function findUncoveredTargets(ignoreText, targets) {
  const patterns = loadPatternsFromText(ignoreText);
  return targets.filter((p) => !isIgnored(p, patterns));
}

/**
 * 불변식 (M) — `.harnessignore` 가 무시하는 경로의 매니페스트 잔존 entry.
 *
 * `.harnessignore` 도입 이후 `buildManifest()` 는 이들을 다시 등록하지 않지만, 도입 이전에
 * 등록된 carry-over 는 자동으로 사라지지 않는다. 남아 있으면 `diffAgainstPackage()` 가
 * `removed-upstream` 으로 분류하고 `--interactive` 가 **[d]elete 삭제**를 제시한다.
 *
 * @param {string} ignoreText
 * @param {string[]} manifestKeys
 * @returns {string[]} 제거 대상 경로 목록 (정렬)
 */
export function findStaleManifestEntries(ignoreText, manifestKeys) {
  const patterns = loadPatternsFromText(ignoreText);
  return manifestKeys.filter((p) => isIgnored(p, patterns)).sort();
}

/**
 * 불변식 (U) — `git add` 이전이라 목록에 반영되지 못한 다운스트림 고유 파일.
 *
 * cross-validate agy 수용 2 (#894 R2). `git ls-files` SSoT 의 유일한 사각이며,
 * 이미 커버되는 경로(디렉토리 압축 하위 등)와 upstream 존재 경로는 제외한다 —
 * 조치가 필요한 것만 남겨야 경고가 잡음이 되지 않는다.
 *
 * @param {string} ignoreText
 * @param {string[]} untrackedCandidates — filterTrackedCandidates 통과분
 * @param {string[]} upstreamPaths
 * @returns {string[]} 조치 필요 경로 (정렬)
 */
export function findUntrackedGaps(ignoreText, untrackedCandidates, upstreamPaths) {
  const patterns = loadPatternsFromText(ignoreText);
  const upstream = new Set(upstreamPaths);
  return untrackedCandidates
    .filter((p) => !upstream.has(p)) // upstream 존재 = ignore 대상 아님
    .filter((p) => !isIgnored(p, patterns)) // 이미 커버됨 = 조치 불요
    .sort();
}

