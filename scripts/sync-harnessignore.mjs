function parseArgs(argv) {
  const opts = {
    check: false,
    selfTest: false,
    pruneManifest: false,
    apply: false, // 안전 기본값 — prune 은 dry-run
    baselineDir: null,
    version: null,
  };
  for (const a of argv.slice(2)) {
    if (a === '--check') opts.check = true;
    else if (a === '--self-test') opts.selfTest = true;
    else if (a === '--prune-manifest') opts.pruneManifest = true;
    else if (a === '--apply') opts.apply = true;
    else if (a === '--dry-run') opts.apply = false;
    else if (a.startsWith('--baseline-dir=')) opts.baselineDir = a.slice('--baseline-dir='.length);
    else if (a.startsWith('--version=')) opts.version = a.slice('--version='.length);
    else {
      console.error(`ERROR: 알 수 없는 인자: ${a}`);
      process.exit(2);
    }
  }
  if (opts.check && opts.pruneManifest) {
    console.error('ERROR: --check 와 --prune-manifest 는 동시 사용 불가');
    process.exit(2);
  }
  return opts;
}

/**
 * 매니페스트 파일 원자적 write (temp + rename).
 * 중간 실패로 매니페스트가 truncate 되면 `harness update` 가 전량 `added` 로 오판해
 * 복구 불가능한 교착이 된다 (CLAUDE.md §매니페스트 최신 ≠ 파일 적용 완료).
 * upstream `writeManifest()` 와 동일 포맷 (2-space indent + trailing newline) 유지.
 *
 * @param {string} absPath
 * @param {object} manifest
 */
function writeManifestAtomic(absPath, manifest) {
  const tmp = `${absPath}.tmp-${process.pid}`;
  writeFileSync(tmp, `${JSON.stringify(manifest, null, 2)}\n`);
  renameSync(tmp, absPath);
}

/**
 * (M) 위반 entry 제거 — dry-run 기본.
 * @param {{rootDir: string, apply: boolean}} args
 * @returns {number} exit code
 */
function pruneManifest({ rootDir, apply }) {
  const abs = join(rootDir, MANIFEST_PATH);
  if (!existsSync(abs)) throw new BaselineUnavailableError(`manifest 부재: ${MANIFEST_PATH}`);
  const ignoreAbs = join(rootDir, IGNORE_PATH);
  if (!existsSync(ignoreAbs)) {
    throw new BaselineUnavailableError(`${IGNORE_PATH} 부재 — 먼저 pnpm sync:harnessignore 실행`);
  }
  const manifest = JSON.parse(readFileSync(abs, 'utf-8'));
  const keys = Object.keys(manifest.files || {});
  const stale = findStaleManifestEntries(readFileSync(ignoreAbs, 'utf-8'), keys);

  console.log(`manifest entries: ${keys.length}`);
  console.log(`${PRUNE_MARKER} ${apply ? '(apply)' : '(dry-run)'} — 제거 대상: ${stale.length}`);
  if (stale.length === 0) {
    console.log(`\n[OK] carry-over 정합 — 제거 대상 없음`);
    return 0;
  }
  for (const p of stale.slice(0, 30)) console.log(`  - ${p}`);
  if (stale.length > 30) console.log(`  … 외 ${stale.length - 30}건`);

  if (!apply) {
    console.log('\n실제 적용: node scripts/sync-harnessignore.mjs --prune-manifest --apply');
    return 0;
  }
  for (const p of stale) delete manifest.files[p];
  writeManifestAtomic(abs, manifest);
  console.log(
    `\n[OK] manifest ${stale.length} entry 제거 → ${Object.keys(manifest.files).length} 잔존`,
  );
  return 0;
}

async function run(opts) {
  const rootDir = '.';
  const baseline = await resolveBaseline(opts, rootDir);

  const upstreamPaths = upstreamTrackedPaths(baseline.dir);
  if (upstreamPaths.length === 0) {
    // baseline 전개 실패를 "부재" 로 흡수하면 전 경로가 ignore 대상이 된다 — 판정 불가로 차단
    throw new BaselineUnavailableError(
      `upstream baseline 에 추적 대상 파일 0건 (${baseline.dir}) — tarball 손상 의심`,
    );
  }
  const localPaths = filterTrackedCandidates(gitTrackedPaths(rootDir));
  const plan = computeIgnorePlan(upstreamPaths, localPaths);

  const block = buildBlock(plan, baseline.version);
  const existing = existsSync(join(rootDir, IGNORE_PATH))
    ? readFileSync(join(rootDir, IGNORE_PATH), 'utf-8')
    : '';
  const next = replaceBlock(existing, block);

  console.log(`baseline: v${baseline.version ?? '(local-dir)'} (${baseline.source})`);
  console.log(`upstream 추적 대상: ${upstreamPaths.length} / 로컬 추적 대상: ${localPaths.length}`);
  console.log(
    `upstream 부재 (ignore 대상): ${plan.targets.length} → 패턴 ${plan.patterns.length}개 ` +
      `(디렉토리 ${plan.dirPatterns.length} / 개별 ${plan.filePatterns.length})`,
  );

  // (S) 안전 — 생성 결과 전문(수동 섹션 포함) 기준. 커밋본이 아니라 next 를 검사해야
  // 수동 섹션 오염이 write 전에 잡힌다.
  const unsafe = findUpstreamPathsIgnored(next, upstreamPaths);
  if (unsafe.length > 0) {
    console.error(`\n${SAFETY_VIOLATION_MARKER}`);
    console.error(
      `  upstream 존재 경로 ${unsafe.length}건이 무시 대상 — added/missing-locally 오분류 유발`,
    );
    for (const p of unsafe.slice(0, 20)) console.error(`    - ${p}`);
    return 1;
  }

  // (K) 완전성
  const uncovered = findUncoveredTargets(next, plan.targets);
  if (uncovered.length > 0) {
    console.error(
      `\n[Harnessignore Coverage Gap] ${uncovered.length}건 미커버 (carry-over 재유입)`,
    );
    for (const p of uncovered.slice(0, 20)) console.error(`    - ${p}`);
    return 1;
  }

  // (U) 미추적 사각 — `git add` 이전 신규 다운스트림 고유 파일 (cross-validate 수용 2).
  //
  // **경고(생성) vs 차단(--check) 비대칭은 의도**다:
  //   - 생성 모드는 "바로잡는" 동작이다. 여기서 차단하면 사각을 해소할 재생성 자체가
  //     막혀 데드락이 된다 → 경고 + `git add` 안내로 충분.
  //   - `--check` 는 게이트다. 미추적 후보가 있으면 커밋된 `.harnessignore` 가 디스크
  //     상태에 대해 불완전하고, 다음 `harness update --apply` 가 그 파일을 carry-over 로
  //     등록한다 → fail-fast 정합상 차단.
  //   - CI 에서는 fresh checkout 이라 미추적 파일이 사실상 0 → 잡음 증가 없음.
  //     발화 지점이 사람이 조치할 수 있는 로컬로 한정된다.
  const untrackedGaps = findUntrackedGaps(
    next,
    filterTrackedCandidates(gitUntrackedPaths(rootDir)),
    upstreamPaths,
  );
  if (untrackedGaps.length > 0) {
    const label = opts.check
      ? '[Harnessignore Untracked Gap]'
      : 'WARN: 미추적 다운스트림 고유 파일';
    const emit = opts.check ? console.error : console.warn;
    emit(`\n${label} ${untrackedGaps.length}건 — 생성 SSoT(git ls-files) 에 아직 없음`);
    for (const p of untrackedGaps.slice(0, 20)) emit(`    - ${p}`);
    emit('  조치: git add <경로> 후 pnpm sync:harnessignore 재실행');
    emit('  미조치 시 다음 `harness update --apply` 가 carry-over 로 재등록한다.');
    if (opts.check) return 1;
  }

  if (opts.check) {
    if (existing !== next) {
      console.error(`\n[Harnessignore Drift] ${IGNORE_PATH} 재생성 필요`);
      console.error('  조치: pnpm sync:harnessignore 실행 후 커밋');
      return 1;
    }
    // (M) 매니페스트 정합 — carry-over 재유입 영구 차단
    const manifestAbs = join(rootDir, MANIFEST_PATH);
    if (!existsSync(manifestAbs)) {
      throw new BaselineUnavailableError(`manifest 부재: ${MANIFEST_PATH}`);
    }
    const manifestKeys = Object.keys(JSON.parse(readFileSync(manifestAbs, 'utf-8')).files || {});
    const stale = findStaleManifestEntries(next, manifestKeys);
    if (stale.length > 0) {
      console.error(
        `\n[Manifest Carry-over] ${stale.length}건 잔존 — removed-upstream 삭제 후보 노출`,
      );
      for (const p of stale.slice(0, 20)) console.error(`    - ${p}`);
      console.error('  조치: node scripts/sync-harnessignore.mjs --prune-manifest --apply');
      return 1;
    }
    console.log(
      `\n[OK] ${IGNORE_PATH} 동기화됨 (안전 ${upstreamPaths.length} / 커버 ${plan.targets.length} / ` +
        `manifest carry-over 0)`,
    );
    return 0;
  }

  if (existing === next) {
    console.log(`\n[OK] 변경 없음 — 패턴 ${plan.patterns.length}개 유지`);
    return 0;
  }
  writeFileSync(join(rootDir, IGNORE_PATH), next);
  console.log(`\n[OK] ${IGNORE_PATH} 재생성 — 패턴 ${plan.patterns.length}개`);
  return 0;
}

async function main() {
  const opts = parseArgs(process.argv);
  if (opts.selfTest) process.exit(runSelfTest());
  try {
    if (opts.pruneManifest) {
      process.exit(pruneManifest({ rootDir: '.', apply: opts.apply }));
    }
    process.exit(await run(opts));
  } catch (err) {
    if (err instanceof BaselineUnavailableError) {
      console.error(`ERROR (판정 불가): ${err.message}`);
      process.exit(2);
    }
    console.error(`ERROR: ${err.stack || err.message}`);
    process.exit(2);
  }
}

