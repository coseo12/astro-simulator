// =============================================================================
// upstream `lib/harnessignore.js` 포팅 (패턴 → 정규식)
// =============================================================================
//
// 불변식 (S) 판정을 **CLI 와 정확히 동형**으로 맞추기 위한 재현이다. upstream 이 문법을
// 확장하면 (`!` 네거티브 등) 본 포팅도 동반 갱신해야 한다.
// 미지원 (upstream 동일): `!` 네거티브, `[abc]` 문자 클래스.

/**
 * @param {string} pattern
 * @returns {RegExp|null} 빈 줄/주석이면 null
 */
export function patternToRegex(pattern) {
  const p = pattern.trim();
  if (!p || p.startsWith('#')) return null;

  const isDir = p.endsWith('/');
  const core = isDir ? p.slice(0, -1) : p;

  let re = '';
  let i = 0;
  while (i < core.length) {
    const ch = core[i];
    if (ch === '*') {
      if (core[i + 1] === '*') {
        re += '.*';
        i += 2;
        if (core[i] === '/') i += 1;
      } else {
        re += '[^/]*';
        i += 1;
      }
    } else if (ch === '?') {
      re += '[^/]';
      i += 1;
    } else if ('.+()|^$[]{}\\'.includes(ch)) {
      re += `\\${ch}`;
      i += 1;
    } else {
      re += ch;
      i += 1;
    }
  }

  // 패턴에 '/' 가 없으면 어느 depth 에서도 매칭 (upstream 동일)
  const anchor = core.includes('/') ? '^' : '(^|/)';
  const tail = isDir ? '(/.*)?$' : '$';
  return new RegExp(anchor + re + tail);
}

/**
 * @param {string} text — `.harnessignore` 전문
 * @returns {RegExp[]}
 */
export function loadPatternsFromText(text) {
  return (text || '')
    .split('\n')
    .map((line) => patternToRegex(line))
    .filter(Boolean);
}

/**
 * @param {string} relPath
 * @param {RegExp[]} patterns
 * @returns {boolean}
 */
export function isIgnored(relPath, patterns) {
  if (!patterns || patterns.length === 0) return false;
  const normalized = relPath.replace(/\\/g, '/');
  return patterns.some((re) => re.test(normalized));
}

