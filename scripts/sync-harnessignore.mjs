#!/usr/bin/env node
/**
 * sync-harnessignore.mjs
 *
 * ADR 20260515 Amendment 17 §결정 7 (#894 PR-B) — `.harnessignore` **자동 생성** + drift 가드.
 *
 * ## 왜 필요한가 (#894 §0-5 실측)
 *
 * upstream `lib/manifest.js::walkTracked()` 는 `TRACKED_DIRS`(`.claude` `.github` `scripts`
 * `docs`) 를 **통째로** 순회해 다운스트림 고유 파일까지 `.harness/manifest.json` 에 등록한다.
 * 본 프로젝트 실측: 359 entry 중 **264 (73.5%) 가 upstream v4.5.0 에 존재하지 않는다**.
 *
 * 이 entry 들은 `diffAgainstPackage()` 에서 전부 `removed-upstream` 으로 분류되고
 * `harness update --interactive` 가 각각에 **`[d]elete 삭제`** 를 제시한다
 * (`lib/update.js` 실측) — **잠재 파괴 경로**다. 부수적으로 `sync-prettierignore.mjs` 가
 * 매니페스트를 그대로 나열하므로 `docs/ops/*` 같은 비-managed 문서가 prettier 대상에서
 * 이탈하는 오염도 만든다 (#795 설계 의도 무효화 — Amendment 17 §결정 7).
 *
 * upstream 은 이미 `.harnessignore` (gitignore 스타일) 를 파싱한다 (`lib/harnessignore.js`
 * + `walkTracked()` 호출부). 따라서 남은 일은 **다운스트림 설정뿐**이다.
 *
 * ## 왜 손으로 유지하지 않는가 (치명적)
 *
 * > **upstream 에 존재하는 경로를 `.harnessignore` 에 넣으면 안 된다.**
 *
 * 넣으면 `walkTracked(cwd)` 에서 그 파일이 빠져 `!inManifest && inPkg && !inUser` →
 * **`added` 로 재도입**되거나 `missing-locally` 로 오분류된다. 수기 목록은 upstream 이
 * 파일을 추가하는 순간 조용히 오염되므로, **upstream 원본과의 대조로 자동 생성**해야 한다.
 * 본 스크립트는 그 대조를 수행하고, 생성 후 **안전 불변식을 assert** 한다 (아래).
 *
 * ## 생성 규칙
 *
 *   대상 = (git 추적 파일 ∩ TRACKED_DIRS/TRACKED_FILES ∖ user-only 카테고리) ∖ upstream 원본
 *
 *   - **디렉토리 압축**: upstream 파일을 하나도 갖지 않는 **가장 얕은** 조상 디렉토리가 있으면
 *     `dir/` 패턴 1줄로 압축한다 (`docs/reports/` 156 파일 → 1줄). 해당 디렉토리에 파일을
 *     추가해도 블록이 변하지 않아 일상 PR 마찰이 0 이다.
 *   - upstream 과 **공유하는** 디렉토리 (`scripts/` `.claude/agents/` 등) 는 압축 불가 —
 *     개별 경로로 나열한다. 이 경우에만 신규 파일 추가 시 `pnpm sync:harnessignore` 가 필요하다.
 *
 * ## 불변식 (fail-fast — CLAUDE.md §가드 설계 원칙, fallback 분기 금지)
 *
 *   (S) **안전**: `.harnessignore` 의 어떤 패턴도 upstream 존재 경로를 매칭하면 안 된다.
 *       위반 시 즉시 exit 1. 수동 섹션(마커 블록 밖)까지 포함해 검사한다.
 *   (K) **완전성**: upstream 부재 대상 파일은 전부 매칭돼야 한다 (carry-over 재유입 차단).
 *   (M) **매니페스트 정합**: `.harnessignore` 가 무시하는 경로는 `.harness/manifest.json` 에
 *       남아 있으면 안 된다. 남으면 `removed-upstream` 으로 분류되어 `--interactive` 의
 *       **[d]elete 삭제 후보**로 계속 제시된다. 위반 시 `--prune-manifest --apply` 안내 후 exit 1.
 *   (U) **미추적 사각**: `git add` 이전 신규 다운스트림 고유 파일 감지 (cross-validate 수용 2).
 *       생성 모드는 **경고**, `--check` 는 **차단** — 비대칭 근거는 `run()` 주석 참조.
 *   (D) **drift**: `--check` 시 생성 결과 ≠ 커밋본이면 exit 1.
 *
 * ## 왜 git 추적 파일 기준인가
 *
 * 디스크 walk 기준으로 만들면 `.claude/scheduled_tasks.lock` 같은 **gitignore 된 런타임
 * 산출물**이 로컬에만 존재해 CI 와 결과가 갈린다 (`--check` 영구 FAIL). git 추적 파일은
 * 어느 환경에서나 동일하므로 결정적이다. 런타임 산출물은 마커 블록 **밖** 수동 섹션에
 * 박제하며, 그 섹션도 불변식 (S) 검사를 받는다.
 *
 * ## 호출
 *
 *   node scripts/sync-harnessignore.mjs              # 재생성 (write)
 *   node scripts/sync-harnessignore.mjs --check      # CI 가드 — drift/안전/정합 위반 시 exit 1
 *   node scripts/sync-harnessignore.mjs --prune-manifest [--apply]
 *                                                    # (M) 위반 entry 제거. dry-run 이 기본
 *   node scripts/sync-harnessignore.mjs --self-test  # 네트워크 미의존 인라인 검증
 *
 *   --baseline-dir=<path>  tarball 대신 로컬 디렉토리를 upstream baseline 으로 사용 (오프라인)
 *   --version=<x.y.z>      baseline 태그 강제 (기본: manifest.harnessVersion)
 *
 * ## exit 코드
 *
 *   0 정상 / 1 불변식 위반 (S)(K)(D) / 2 판정 불가 (네트워크·태그 부재·manifest 부재)
 *   — `verify-harness-upstream-baseline.mjs` 와 동일 규약. 판정 불가를 PASS 로 흡수하지 않는다.
 *
 * ## 관련
 *   - ADR docs/decisions/20260515-harness-managed-divergent-pattern.md §Amendment 17
 *   - 자매 스크립트: scripts/sync-prettierignore.mjs (동형 마커 블록 패턴, #229)
 *   - baseline 취득 재사용: scripts/verify-harness-upstream-baseline.mjs (`resolveBaseline`)
 *   - 절차 SSoT: .claude/commands/harness-update.md §7 / scripts/harness-update-safe.sh
 *   - 이슈: coseo12/astro-simulator#894
 */
