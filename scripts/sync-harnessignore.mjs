/**
 * `walkTracked()` 가 매니페스트에 등록할 **후보** 경로만 남기는 필터.
 * user-only 카테고리는 upstream 도 등록하지 않으므로 `.harnessignore` 대상이 아니다
 * (넣으면 `docs/decisions/` 100+ 줄이 무의미하게 부풀어 리뷰 신호를 죽인다).
 *
 * @param {string[]} relPaths
 * @returns {string[]}
 */
export function filterTrackedCandidates(relPaths) {
  return relPaths
    .filter((p) => TRACKED_FILES.includes(p) || TRACKED_DIRS.some((d) => p.startsWith(`${d}/`)))
    .filter((p) => categorize(p) !== 'user-only')
    .sort();
}

/**
 * 로컬 git 추적 파일 목록 (결정적 — CI/로컬 동일).
 * @param {string} rootDir
 * @returns {string[]}
 */
function gitTrackedPaths(rootDir) {
  let out;
  try {
    out = execFileSync('git', ['-C', rootDir, 'ls-files', '-z'], {
      encoding: 'utf-8',
      maxBuffer: 64 * 1024 * 1024,
    });
  } catch (err) {
    throw new BaselineUnavailableError(`git ls-files 실패: ${err.message}`);
  }
  return out.split('\0').filter(Boolean);
}

/**
 * git **미추적 + 비-gitignore** 파일 목록 (cross-validate agy 수용 2 — #894 R2 라운드).
 *
 * `git ls-files` SSoT 는 결정성(CI ↔ 로컬 동일) 때문에 유지하지만, **`git add` 이전 신규
 * 파일이 목록에서 누락되는 사각**이 있다. 이 결함은 본 PR 안에서 실제로 발화했다 —
 * `scripts/harness-update-safe.sh` 를 새로 만든 커밋에서 `.harnessignore` 가 자신을
 * 누락했고, 커밋 직후 `--check` 가 exit 1 로 잡았다 (한 라운드 늦은 검출).
 *
 * `git status --porcelain` 은 **gitignore 된 파일을 제외**하므로 `.claude/scheduled_tasks.lock`
 * 같은 런타임 산출물은 여기 잡히지 않는다 (수동 섹션 담당 — 역할 분리 유지).
 *
 * @param {string} rootDir
 * @returns {string[]} 미추적 경로 (repo 상대)
 */
function gitUntrackedPaths(rootDir) {
  let out;
  try {
    out = execFileSync(
      'git',
      ['-C', rootDir, 'status', '--porcelain', '--untracked-files=all', '-z'],
      { encoding: 'utf-8', maxBuffer: 64 * 1024 * 1024 },
    );
  } catch (err) {
    throw new BaselineUnavailableError(`git status 실패: ${err.message}`);
  }
  // `-z` 포맷: `XY <path>\0` (rename 은 `\0` 이 하나 더 붙지만 `??` 에는 없다)
  return out
    .split('\0')
    .filter(Boolean)
    .filter((entry) => entry.startsWith('?? '))
    .map((entry) => entry.slice(3));
}

/**
 * upstream baseline 디렉토리의 추적 대상 경로 목록.
 * @param {string} baselineDir
 * @returns {string[]}
 */
function upstreamTrackedPaths(baselineDir) {
  const out = [];
  const walk = (rel, abs) => {
    if (!existsSync(abs)) return;
    const st = statSync(abs);
    if (st.isDirectory()) {
      for (const entry of readdirSync(abs)) walk(rel ? `${rel}/${entry}` : entry, join(abs, entry));
    } else if (st.isFile()) {
      out.push(rel);
    }
  };
  for (const f of TRACKED_FILES) walk(f, join(baselineDir, f));
  for (const d of TRACKED_DIRS) walk(d, join(baselineDir, d));
  return filterTrackedCandidates(out);
}

