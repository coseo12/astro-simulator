/**
 * pr-body-code-regions.mjs
 *
 * PR 본문에서 **코드 영역**(fenced block + 인라인 코드 스팬)을 제거하는 공유 전처리.
 * 부작용 없는 순수 함수 모듈이다 (import 시 아무것도 실행하지 않음 / 의존성 0 / 네트워크 0).
 *
 * **왜 별도 모듈인가 (#1190).** `scripts/stage-label-decision.mjs` 의 `parseLinkedIssue` 와
 * `scripts/auto-close-issue-parser.mjs` 의 `parseCloseTargets` 는 둘 다 마크다운을 해석하지
 * 않아, 본문에 **예시로** 적은 `<키워드> #<번호>` 를 코드 스팬 안이어도 진짜 링크로 읽었다.
 * 전자는 라벨을 엉뚱한 이슈에 부착하고 후자는 **무관한 이슈를 close** 한다. 두 파서가 각자
 * 전처리를 들면 그 자체가 새 drift 원이므로 전처리를 1곳으로 끌어내고 양쪽이 import 한다 —
 * 사본을 만들지 않는 것이 "drift 감지" 보다 근본이다 (`scripts/upstream-only-allowlist.mjs`
 * (#1005) 가 같은 판단의 선례 / CLAUDE.md §drift 근본 제거).
 *
 * ⚠️ **공유 범위는 전처리까지다.** 두 파서의 키워드 집합(3종 vs 9종) · 매치 수(첫 매치 vs
 * 전 매치) · dedup 유무는 여전히 각자이며, 그것이 `stage-label-decision.mjs` §의도적 비재사용
 * 판정이 계속 유효한 이유다.
 *
 * ## 왜 저장소의 기존 마스킹 함수를 쓰지 않는가 (사전 탐색 결과 — CLAUDE.md §신규 함수 ≠ 신규 구현)
 *
 * 유사 구현 `3` 개가 이미 있고 전부 검토했다. 재사용하지 않은 이유는 「몰라서」가 아니라
 * **의미론이 측정 대상과 다르기 때문**이며, 차이는 아래 한계 항목들과 직접 맞물린다:
 *   - `verify-docs-links.mjs` 의 `maskCode` — 비재사용 사유는 **비공개**(export 되지 않음)
 *     이고, export 로 승격하면 그 가드의 소비처 계약까지 함께 건드리게 된다는 것이다.
 *     ⚠️ **의미론 차이 자체는 본 용도에 유리한 쪽이다** — 인라인 스팬이 개행을 넘지
 *     않고(부정 문자클래스에 \n 포함) fence 짝짓기가 라인 앵커 + 역참조라, 아래 한계 2 는
 *     아예 없고 한계 3 의 발화 조건은 더 좁다. tilde fence 도 인식한다(→ 한계 5 가
 *     기각한 확장). 「대안이 열등해서 안 썼다」로 읽지 말 것.
 *     다만 그 차이들이 아래 실측 표의 전제를 바꾸므로 수치를 그대로 옮길 수는 없다.
 *   - `verify-ssot-trigger-wording.mjs` 의 `stripFencedBlocks` / `maskInlineCode` — 상태 있는
 *     라인 스캐너 + **본문만** 마스킹하고 백틱은 남긴다(강조 구분자 짝 맞추기 전용).
 *     백틱이 남으면 본 용도에서는 후속 스팬 짝짓기가 어긋난다.
 *   - `verify-md-tilde.mjs` 의 `scanContent` — 위반 라인 열거가 목적이라 문자열을 반환하지 않는다.
 * ⚠️ 그래서 본 모듈은 같은 클래스의 **네 번째** 구현이다. 넷을 하나로 합치는 것은 세 소비처의
 * 의미론을 동시에 바꾸는 작업이라 #1190 의 명시적 비-범위이며, 합치려면 각 소비처의 실측을
 * 다시 떠야 한다. 이 사실을 적어 두는 이유는 **미래에 통합을 검토할 사람이 넷이 있다는 것을
 * 알고 시작하도록** 하기 위해서다.
 *
 * ## 계약
 *
 * stripCodeRegions(body) -> string
 *
 * - 입력이 문자열이 아니면(null / undefined 포함) 빈 문자열을 반환한다. GitHub REST 는
 *   본문이 비어 있을 때 body 를 null 로 준다. 현재 세 호출처가 모두 자기 앞에서
 *   falsy 를 걸러내지만, 그 가드가 하나라도 사라지면 여기가 마지막 방어선이다.
 * - 처리 순서는 **fenced block 먼저, 인라인 스팬 나중**이다. 순서를 뒤집으면 fenced
 *   마커의 백틱 3개가 인라인 규칙에 먼저 잡혀 블록이 조각난다.
 * - 치환 문자는 **공백 1개**다 (빈 문자열이 아닌 이유는 아래 한계 4).
 * - 멱등이다: 1회 통과 후 백틱이 남지 않으므로 2회 적용이 1회와 같다
 *   (실측 690/690 에서 위반 0).
 * - 정규식은 lazy 수량자 + 부정 문자클래스 + 리터럴 종결자 조합이라 중첩 모호성이
 *   없다. GitHub 이 강제하는 본문 상한 65536 자에서 적대적 입력 7종(미닫힘 fence
 *   반복 / 백틱 단독 대량 / 2백틱 반복 / fence 시작 대량 / 백틱·개행 교대 / 단일
 *   미닫힘 fence / fence 홀수 + 잔여)을 측정했다. 기록에 남은 최악 관측값은 3회 실행에서
 *   0.52 / 0.71 / 1.16 ms 다 (Node v24.14.0 — 각각 reviewer 재현 / dev 실행 / 설계 단계).
 *   ⚠️ 세 가지가 이 기록의 한계다: (1) 7종은 손으로 고른 표본이지 증명이 아니고,
 *   (2) 밀리초 수치는 기계 상태이지 저장소 불변식이 아니라 재실행마다 달라지며,
 *   (3) 그래서 **어떤 부등식도 쓰지 않는다** — 초판이 「1ms 미만」이라고 적었다가
 *   같은 문장이 인용한 1.16 에 반증됐다 (PR #1191 reviewer B1). 남기는 것은 위
 *   3회 관측값 자체이고, 그것이 「초 단위로 폭주한다」와 구분되는 유일한 기록이다.
 *
 * ## 알려진 한계 (휴리스틱이지 마크다운 파서가 아니다)
 *
 * 측정: 2026-09-03 / 표본 = 머지 PR 전수 690 건 (#41 ~ #1189).
 * 재도출 술어:
 *   gh pr list --state merged --limit 2000 --json number,body > merged.json
 *   각 본문 b 에 대해 parse(b) 와 parse(stripCodeRegions(b)) 를 대조.
 * ⚠️ 아래 수치는 저장소 상태이지 불변식이 아니다. 표본이 머지 PR **최종판**이라
 *    수정 전 초판이 빠져 있으므로 노출 수치는 **하한**이다 (오차 방향은 본 전처리를
 *    채택할 근거를 강화한다). 상한으로 읽지 말 것.
 *
 * 한계 1 — 백슬래시 이스케이프. `\` + 백틱은 렌더링상 코드 스팬이 아니라 리터럴
 *   백틱인데 본 함수는 코드 스팬으로 오인한다.
 *     노출(본문에 해당 시퀀스 등장) 56/690 · 그중 결과가 달라진 건 1/690 (#422)
 *     · 그중 저자 의도와 어긋난 건 0/690.
 *   ⚠️ 이 한계는 **의도적으로 처방하지 않는다.** 이스케이프 인식 구현(sentinel 격리)
 *      을 실제로 돌려 690 건에 대조한 결과, #422 의 정정을 잃고(null -> 411, 저자
 *      의도 위반) #1070 에서 진짜 링크를 파괴한다 — 그 PR 의 `### 관련 이슈` 절은
 *      실제 close 지시 3행이고, 처방은 parseLinkedIssue 를 1045 -> null 로,
 *      parseCloseTargets 를 [1045,1047,1051] -> [] 로 만든다. 즉 처방이 현행
 *      채택안보다 엄격히 나쁘다 — 정정 3·회귀 0 이 정정 2·회귀 1 이 된다.
 *      잔여: 다른 구현이 #1070 회귀를 피할 수 있으나 그 판정에는 문자 단위 스캐너
 *      = 사실상 CommonMark 파서가 필요하고 그것은 명시적 비-범위다.
 *   재판정 트리거: 이스케이프된 백틱 안에 **진짜** close 지시가 있는 PR 이 실제로
 *      관측될 때. (시간 기준 아님.)
 *
 * 한계 2 — 문단 경계 미준수. 홀수 개의 백틱이 문단을 건너 짝지어 사이의 텍스트를
 *   통째로 삼킨다.
 *     노출(fenced 제거 후 백틱 개수가 홀수인 본문) 3/690 (#1077 · #1044 · #481)
 *     · 그중 결과가 달라진 건 0/690.
 *
 * 한계 3 — fence 짝짓기가 비탐욕 쌍 단위다. fence 마커가 홀수 개면 마지막 하나가
 *   짝을 찾지 못한 채 남는다.
 *     노출(fence 마커 개수가 홀수인 본문) 0/690 · 결과가 달라진 건 0/690.
 *     ⚠️ 이 `0` 은 술어 선택에 강건하다 — 줄 선두 ``` / 들여쓰기 허용 / 본문 어디든,
 *     세 술어 전부 0/690 이다 (셋을 다 돌린 이유는 #1134 가 「행 선두만」 이라는
 *     좁은 술어로 뚫린 선례이기 때문이다).
 *
 * 한계 4 — 치환 문자가 공백 1개다. 없던 공백이 생겨 "키워드 + 공백 + #N" 형태를
 *   만들어낼 수 있다 (예: 키워드와 #N 사이에 공백 없이 스팬만 있는 본문).
 *   치환을 빈 문자열로 하면 이 클래스는 사라지지만 대신 조각이 이어붙어 키워드나
 *   번호 자체가 합성되는 클래스 2종이 생긴다 — 그중 번호 합성은 **다른 이슈 번호를
 *   만들어내므로** 본 모듈이 없애려는 피해와 같은 방향이다. 그래서 공백을 택했다.
 *     이 한계 자체의 노출 — 본 전처리가 **없던 매치를 만든** PR — 은 0/690 이다.
 *     델타 방향 분해(690건): 매치 생성 0 · 매치 제거(fail-safe) 3 (#660 · #431 · #422)
 *     · 번호 변경 0. `parseCloseTargets` 에 없던 번호가 추가된 PR 도 0 이다.
 *     두 전략(공백 vs 빈 문자열)의 결과가 갈리는 PR 0/690 (실측).
 *
 * 한계 5 — tilde fence(~~~) 미지원. GFM 은 물결표 3개 이상도 코드 블록으로 인정하나
 *   본 함수는 백틱 fence 만 제거한다.
 *     노출(줄 선두 ~~~ 를 가진 본문) 0/690 · 본문 어디에든 ~~~ 가 등장하는 본문
 *     1/690 · tilde 도 제거하도록 확장했을 때 결과가 달라지는 PR 0/690.
 *   ⚠️ 확장하지 않는다. 이득이 실측 0 인 반면, ~~~ 짝짓기를 추가하면 GFM 취소선
 *      (~~text~~, 실측 8/690 이 사용)이 늘어선 본문에서 엉뚱한 구간을 삼키는
 *      새 오탐 클래스가 생긴다. 노출 0 짜리 이득에 오탐 표면을 사는 거래다.
 *   재판정 트리거: 줄 선두 ~~~ 를 쓴 PR 본문이 실제로 관측될 때.
 *
 * 실패 방향은 fail-safe 다: 위 한계로 틀리면 **진짜 링크를 놓치는** 쪽이고, 그것은
 * 라벨 미전이 / auto-close 미발동 = 기존 수동 폴백(docs/ops/operational-friction.md
 * §1)이 받는다. 반대 방향(무관한 이슈를 건드림)은 본 모듈이 제거한 것이다.
 *
 * 회귀 가드: 전용 테스트 파일을 두지 않는다. 본 함수의 판별력은 두 소비처의 기존 suite
 * (`stage-label-decision.test.mjs` U12-1~U12-4 · U13 / `auto-close-issue-parser.mjs --self-test`)
 * 가 변이 M8~M11 **전건 단독 사살**로 실증한다 (#1190 설계 §변이 매트릭스).
 */

/** fenced code block — 여는 ``` 부터 가장 가까운 닫는 ``` 까지 (비탐욕 쌍 단위 — 한계 3). */
const FENCED_BLOCK_RE = /```[\s\S]*?```/g;

/** 인라인 코드 스팬 — 백틱 쌍. 개행을 넘는다 (그 대가가 한계 2). */
const INLINE_SPAN_RE = /`[^`]*`/g;

/** 치환 문자 — 빈 문자열이 아닌 이유는 §알려진 한계 4. */
const REPLACEMENT = ' ';

/**
 * PR 본문에서 코드 영역(fenced block + 인라인 스팬)을 공백 1개로 치환한다.
 *
 * @param {string|null|undefined} body
 * @returns {string} 코드 영역이 제거된 본문 (입력이 문자열이 아니면 빈 문자열)
 */
export function stripCodeRegions(body) {
  if (typeof body !== 'string') return '';
  // ⚠️ 순서 고정 — fenced 먼저. 뒤집으면 fence 마커의 백틱 3개가 인라인 규칙에 먼저
  // 잡혀 블록이 조각난다 (§계약).
  return body.replace(FENCED_BLOCK_RE, REPLACEMENT).replace(INLINE_SPAN_RE, REPLACEMENT);
}
