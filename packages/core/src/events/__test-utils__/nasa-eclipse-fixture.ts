import { MILLIS_PER_DAY, UNIX_EPOCH_JD } from '../../time/julian-date.js';

export type NasaSolarEclipseType = 'total' | 'annular' | 'partial' | 'hybrid';
export type NasaLunarEclipseType = 'total' | 'partial' | 'penumbral';

/** `[YYYY-MM-DD, HH:MM:SS (TD), 종류]`. */
export type NasaEclipseRow<T extends string> = readonly [date: string, td: string, type: T];

/**
 * 행의 최대식 시각 [JD TD]. 원 목록에는 초가 `60` 인 행이 있다 (월식 7건 — 예 `1907-01-29 13:37:60`, `LEdecade1901`) — 원값을
 * 그대로 두고 `Date.UTC` 의 자리 올림으로 다음 분 0초로 읽는다. `isoToJulianDate` 는 이 문자열을 거부해 쓰지 않는다.
 */
export function nasaEclipseJulianDate(row: NasaEclipseRow<string>): number {
  const [y, mo, d] = row[0].split('-').map(Number) as [number, number, number];
  const [hh, mm, ss] = row[1].split(':').map(Number) as [number, number, number];
  return Date.UTC(y, mo - 1, d, hh, mm, ss) / MILLIS_PER_DAY + UNIX_EPOCH_JD;
}

